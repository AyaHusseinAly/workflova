function t(type: Candidate['timeline'][0]['type'], text: string, at = '2026-05-01 10:00'): Candidate['timeline'][0] {
  return { type, text, at };
}

export function getSeedCandidatesForTemplate(templateId: WorkspaceTemplateId): Candidate[] {
  switch (templateId) {
    case 'recruitment':
      return recruitmentSeeds();
    case 'real-estate':
      return realEstateSeeds();
    case 'student-admission':
      return studentAdmissionSeeds();
    case 'insurance-claims':
      return insuranceSeeds();
    case 'order-fulfillment':
      return orderSeeds();
    case 'customer-onboarding':
      return customerOnboardingSeeds();
    default:
      return recruitmentSeeds();
  }
}

